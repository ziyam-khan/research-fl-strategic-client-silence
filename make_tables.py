#!/usr/bin/env python3
"""Generate LaTeX tables for master/ from the frozen analysis output and the exploratory module, so no
number in the paper is copied by hand.

Usage: python3 make_tables.py     (stdlib; writes master/tables/*.tex)
"""
import os, re, statistics as st
import explore_v2 as E

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "tables")
os.makedirs(OUT, exist_ok=True)
SYM = {"≥": r"$\geq$", "≤": r"$\leq$", "ρ": r"$\rho$", "Δ": r"$\Delta$", "−": r"$-$", "×": r"$\times$",
       "ε": r"$\varepsilon$", "±": r"$\pm$", "α": r"$\alpha$", "%": r"\%", "_": r"\_", "&": r"\&",
       "→": r"$\to$", "≈": r"$\approx$", "∈": r"$\in$", "<": r"$<$", ">": r"$>$", "\\|": r"$|$"}


def tex(s):
    s = s.replace("\\|", "\x00")
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    for k, v in SYM.items():
        if k != "\\|":
            s = s.replace(k, v)
    return s.replace("\x00", r"$|$").replace("$$", "")


def verdicts():
    """Every pre-registered verdict, verbatim from ANALYSIS-v2.md (written by the frozen analyze_v2.py)."""
    rows = []
    for line in open(os.path.join(HERE, "ANALYSIS-v2.md")):
        m = re.match(r"^\| (\w+) \| (.+?) \| \*\*(\w+)\*\* \| (.+) \|$", line.strip())
        if m:
            rows.append(m.groups())
    body = "\n".join(f"{i} & {tex(c)} & \\textsc{{{v.lower()}}} & {tex(e)} \\\\" for i, c, v, e in rows)
    with open(os.path.join(OUT, "verdicts.tex"), "w") as f:
        f.write("% generated by make_tables.py from ANALYSIS-v2.md; do not edit\n"
                "\\begin{table*}[!t]\\centering\\scriptsize\n"
                "\\caption{All pre-registered claims and their verdicts (5 seeds, paired $t$, df 4). "
                "Generated from the frozen analysis script's output.}\\label{tab:verdicts}\n"
                "\\begin{tabularx}{\\textwidth}{@{}l>{\\raggedright\\arraybackslash}p{0.33\\textwidth}l"
                ">{\\raggedright\\arraybackslash}X@{}}\\toprule\n"
                "ID & Claim & Verdict & Evidence (pp, 95\\% CI) \\\\\\midrule\n" + body +
                "\n\\bottomrule\\end{tabularx}\\end{table*}\n")
    return len(rows)


def gains():
    """Exploratory: harm and every defence's gain over FedAvg, all datasets x attacks."""
    C = E.load_all()
    rows = E.holm(E.gain_matrix(C))

    def cell(r):
        txt = f"{r['mean']:+.2f} ({(r['hi'] - r['lo']) / 2:.2f})"
        return f"\\textbf{{{txt}}}" if (r["lo"] > 0 or r["hi"] < 0) else txt

    lines = []
    for ds in E.DS:
        for k, atk in enumerate(E.ATK):
            sel = {r["what"]: r for r in rows if r["ds"] == ds and r["atk"] == atk}
            lab = E.DS_LABEL[ds] if k == 0 else ""
            lines.append(f"{lab} & {E.ATK_LABEL[atk]} & " + " & ".join(cell(sel[w]) for w in ("harm",) + E.METHODS) + " \\\\")
        lines.append("\\midrule" if ds != E.DS[-1] else "")
    with open(os.path.join(OUT, "gains.tex"), "w") as f:
        f.write("% generated by make_tables.py from explore_v2.py; do not edit\n"
                "\\begin{table*}[!t]\\centering\\footnotesize\n"
                "\\caption{Exploratory sweep (not pre-registered). FedAvg harm, and each defence's gain over FedAvg, "
                "in pp: mean over 5 seeds (95\\% CI half-width). Bold: CI excludes 0. "
                f"Of these {len(rows)} tests, {sum(r['holm'] for r in rows)} {'survives' if sum(r['holm'] for r in rows) == 1 else 'survive'} a Holm correction.}}\\label{{tab:gains}}\n"
                "\\begin{tabular}{@{}llrrrrr@{}}\\toprule\n"
                "Dataset & Attack & FedAvg harm & AAWA v1 & AAWA v2 & MIFA & Mem-10 \\\\\\midrule\n"
                + "\n".join(lines) + "\n\\bottomrule\\end{tabular}\\end{table*}\n")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    n = verdicts()
    gains()
    print(f"wrote verdicts.tex ({n} claims) and gains.tex")
